// lib/synonyms.mjs —— 同义扩展：她说"回两条"，记录里是"发两条"
//
// 起因（2026-10-29 复盘）：她记不住旧事，很大一部分不是没存，是**词对不上**。
// 分词是中文二元组（"回两""两条"），所以这里按**字**换：
// 把没人见过的那个二元组，按同义字换成可能的写法再试一次。
//
// 只在原词「她从没见过」（索引里没有）时才扩展——见过的词不动，
// 免得把原本安静的问题搅出水花（召回噪声比漏召回更难查）。

/** 单字同义表：只收这一路上真踩过的、以及日常最常换的 */
const CHAR = new Map([
  ['回', ['发', '答']],
  ['发', ['回', '送']],
  ['说', ['讲', '聊']],
  ['讲', ['说', '聊']],
  ['聊', ['说', '讲']],
  ['看', ['瞧', '瞅']],
  ['瞧', ['看']],
  ['瞅', ['看']],
  ['图', ['片', '照']],
  ['片', ['图', '照']],
  ['睡', ['眠', '困']],
  ['困', ['睡', '累']],
  ['累', ['困', '乏']],
  ['钱', ['费', '账']],
  ['费', ['钱']],
  ['想', ['念', '觉']],
  ['做', ['弄', '搞']],
  ['弄', ['做', '搞']],
  ['好', ['行', '成']],
  ['要', ['想', '得']],
  ['快', ['速', '急']],
  ['怕', ['惧', '慌']],
  ['气', ['怒', '恼']],
])

const CJK = /[\u3400-\u9fff]/

/**
 * 给一个"她从没见过"的词找替身。
 * @param {string} token 二元组或单字
 * @returns {string[]} 可能的写法（不含原词）
 */
export function synonymTokens(token = '') {
  const t = String(token ?? '')
  if (!t || !CJK.test(t)) return []
  const out = new Set()
  for (let i = 0; i < t.length; i += 1) {
    for (const alt of CHAR.get(t[i]) ?? []) {
      out.add(t.slice(0, i) + alt + t.slice(i + 1))
    }
  }
  out.delete(t)
  return [...out]
}

/** 表里有没有这个字（体检/测试用） */
export function knownChar(ch = '') {
  return CHAR.has(String(ch ?? ''))
}